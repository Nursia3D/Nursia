using AssetManagementBase;
using Microsoft.Xna.Framework;
using Newtonsoft.Json;
using Nursia.Attributes;
using Nursia.Data.Landscape;
using Nursia.Materials;
using Nursia.Rendering;
using Nursia.Serialization;
using Nursia.Utilities;
using System;
using System.ComponentModel;

namespace Nursia.SceneGraph.Landscape
{
	[EditorInfo("Base")]
	public class TerrainNode : SceneNode, IHasExternalAssets
	{
		private class FillRenderPartsContext
		{
			public IMaterial Material;
			public Matrix World;
			public Matrix WorldViewProjection;
			public IRenderBatch RenderBatch;
			public Plane? ClipPlane;
		}

		private readonly Terrain _terrain = new Terrain();
		private readonly FillRenderPartsContext _fillRenderPartsContext = new FillRenderPartsContext();

		/// <summary>
		/// Unique terrain id generated by the editor
		/// </summary>
		[Browsable(false)]
		public int EditorId { get; set; }

		[Browsable(false)]
		[JsonIgnore]
		public Terrain Terrain => _terrain;

		[Category("Terrain")]
		[JsonIgnore]
		public HeightField HeightField
		{
			get => _terrain.HeightField;

			set => _terrain.HeightField = value;
		}

		[Category("Terrain")]
		[JsonIgnore]
		public string HeightFieldSize => HeightField != null ? $"{HeightField.Columns}x{HeightField.Rows}" : "null";

		[Category("Terrain")]
		[Browsable(false)]
		public string HeightFieldPath { get; set; }

		[Category("Terrain")]
		public Vector3 TerrainSize
		{
			get => _terrain.Size;

			set => _terrain.Size = value;
		}

		[Category("Terrain")]
		public int DetailLevels
		{
			get => _terrain.DetailLevels;

			set => _terrain.DetailLevels = value;
		}

		[Category("Terrain")]
		public int PatchSize
		{
			get => _terrain.PatchSize;

			set => _terrain.PatchSize = value;
		}

		[Category("Terrain")]
		public float VerticalSkirtScale
		{
			get => _terrain.VerticalSkirtScale;

			set => _terrain.VerticalSkirtScale = value;
		}

		public IMaterial Material { get; set; } = new TerrainMaterial();

		public override BoundingBox? BoundingBox => _terrain.BoundingBox;

		public override void Load(AssetManager assetManager)
		{
			base.Load(assetManager);

			if (!string.IsNullOrEmpty(HeightFieldPath))
			{
				HeightField heightField;
				using (var stream = assetManager.Open(HeightFieldPath))
				{
					heightField = HeightField.FromStreamHf(stream);
				}

				_terrain.HeightField = heightField;
			}

			var hasExternalAssets = Material as IHasExternalAssets;
			if (hasExternalAssets != null)
			{
				hasExternalAssets.Load(assetManager);
			}
		}

		public Vector3? FindPosition(Ray ray) => _terrain.FindPosition(GlobalTransform, ray);

		private static readonly Vector3[] _corners = new Vector3[8];

		private static readonly Func<QuadTreeNode<TerrainPatch>, FillRenderPartsContext, bool> _fillRenderPartsAction = (node, context) =>
		{
			var bb = node.BoundingBox.Transform(ref context.World);
			if (context.RenderBatch.Camera.Frustum.Contains(bb) == ContainmentType.Disjoint)
			{
				return false;
			}

			if (node.IsLeaf)
			{
				// Determine LOD
				// First of all transform the bounding box to NDC coordinates
				// Determine x, y bounds
				var min = new Vector2(float.MaxValue, float.MaxValue);
				var max = new Vector2(float.MinValue, float.MinValue);

				node.BoundingBox.GetCorners(_corners);
				for (var i = 0; i < _corners.Length; ++i)
				{
					var c = _corners[i];
					var c2 = new Vector4(c.X, c.Y, c.Z, 1.0f);
					Vector4 r;
					Vector4.Transform(ref c2, ref context.WorldViewProjection, out r);

					// Finish the projection
					var mult = 1.0f / r.W;
					r.X *= mult;
					r.Y *= mult;

					min.X = Math.Min(min.X, r.X);
					min.Y = Math.Min(min.Y, r.Y);

					max.X = Math.Max(max.X, r.X);
					max.Y = Math.Max(max.Y, r.Y);
				}

				// NDC viewport area is 4(x and y go from -1 to 1)
				// So we calculate LOD following way: 4 / 10 / boundingBoxArea = 0.4f / boundingBoxArea
				var boundingBoxArea = (max.X - min.X) * (max.Y - min.Y);

				var lod = 0;
				if (boundingBoxArea.IsZero())
				{
					// Last lod
					lod = node.Data.Levels.Count - 1;
				}
				else
				{
					lod = (int)(0.03f / boundingBoxArea);
					lod = lod.Clamp(0, node.Data.Levels.Count - 1);
				}

				// Don't do additional bounding box in the BatchJob, since it had been done already in the above code
				context.RenderBatch.BatchJob(context.Material, context.World, node.Data.Levels[lod], cullByBoundingBox: false, clipPlane: context.ClipPlane);
			}

			return true;
		};

		protected internal override void Render(IRenderBatch batch)
		{
			base.Render(batch);

			if (Material == null || _terrain.Patches == null)
			{
				return;
			}

			_fillRenderPartsContext.Material = Material;
			_fillRenderPartsContext.World = GlobalTransform;
			_fillRenderPartsContext.WorldViewProjection = GlobalTransform * batch.Camera.ViewProjection;
			_fillRenderPartsContext.RenderBatch = batch;

			_terrain.PatchTreeRecursiveAction(_fillRenderPartsAction, _fillRenderPartsContext);

			_fillRenderPartsContext.Material = null;
			_fillRenderPartsContext.RenderBatch = null;
		}

		public float GetHeight(Vector3 worldPos)
		{
			// From world pos to model
			var pos = worldPos;
			pos = Vector3.Transform(pos, InverseGlobalTransform);

			return _terrain.GetHeight(new Vector2(pos.X, pos.Z));
		}

		public Vector3 ComputeNormal(Vector2 worldPos)
		{
			// From world pos to model
			var pos = worldPos;
			pos = Vector2.Transform(pos, InverseGlobalTransform);

			return _terrain.ComputeNormal(pos);
		}

		//internal void DebugDrawBoundingBoxes(Camera camera) => _terrain.DebugDrawBoundingBoxes(GlobalTransform, camera);

		protected override SceneNode CreateInstanceCore() => new TerrainNode();

		protected override void CopyFrom(SceneNode node)
		{
			base.CopyFrom(node);

			var terrainNode = (TerrainNode)node;

			HeightField = terrainNode.HeightField;
			HeightFieldPath = terrainNode.HeightFieldPath;
			TerrainSize = terrainNode.TerrainSize;
			DetailLevels = terrainNode.DetailLevels;
			PatchSize = terrainNode.PatchSize;
			VerticalSkirtScale = terrainNode.VerticalSkirtScale;

			if (terrainNode.Material != null)
			{
				Material = terrainNode.Material.Clone();
			}
		}
	}
}
